// Generates lib/device/engine/migrations.generated.ts from drizzle/.
//
// The device database must replay exactly the same schema history as the server
// database, so that a server file can be imported into the browser and a device
// file can be inspected with server tooling. This mirrors drizzle's own
// readMigrationFiles() in node_modules/drizzle-orm/migrator.js: journal order,
// the "--> statement-breakpoint" split, the sha256 of the full file content,
// and the journal "when" value used as __drizzle_migrations.created_at.
//
// Usage:
//   node scripts/gen-device-migrations.mjs          write the generated module
//   node scripts/gen-device-migrations.mjs --check  exit 1 if it is stale

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationsFolder = path.join(root, "drizzle");
const outFile = path.join(root, "lib", "device", "engine", "migrations.generated.ts");

export function readDrizzleMigrations(folder = migrationsFolder) {
  const journalPath = path.join(folder, "meta", "_journal.json");
  if (!fs.existsSync(journalPath)) throw new Error("Missing " + journalPath);
  const journal = JSON.parse(fs.readFileSync(journalPath).toString());
  return journal.entries.map((entry) => {
    // Same read as drizzle: Buffer.toString() of the raw file, no trimming.
    const query = fs.readFileSync(path.join(folder, entry.tag + ".sql")).toString();
    return {
      tag: entry.tag,
      when: entry.when,
      hash: crypto.createHash("sha256").update(query).digest("hex"),
      statements: query.split("--> statement-breakpoint"),
    };
  });
}

export function renderModule(migrations) {
  return [
    "// GENERATED by scripts/gen-device-migrations.mjs from drizzle/. Do not edit.",
    "// Regenerate with: npm run device:migrations",
    "",
    "export interface DeviceMigration {",
    "  /** Journal tag, e.g. 0000_mute_rictor. */",
    "  tag: string;",
    "  /** Journal timestamp; stored as __drizzle_migrations.created_at. */",
    "  when: number;",
    "  /** sha256 of the full .sql file, identical to drizzle's migrator. */",
    "  hash: string;",
    "  /** The file split on drizzle's statement breakpoint marker. */",
    "  statements: string[];",
    "}",
    "",
    "export const DEVICE_MIGRATIONS: readonly DeviceMigration[] = " +
      JSON.stringify(migrations, null, 2) +
      ";",
    "",
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const expected = renderModule(readDrizzleMigrations());
  if (check) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
    if (current !== expected) {
      console.error("FAIL  lib/device/engine/migrations.generated.ts is stale. Run: npm run device:migrations");
      process.exit(1);
    }
    console.log("PASS  device migrations are up to date");
    return;
  }
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, expected, "utf8");
  console.log("wrote " + path.relative(root, outFile));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
